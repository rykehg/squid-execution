using System.Net;
using System.Text.Json;
using Microsoft.Extensions.Logging.Abstractions;
using SkiaSharp;
using Squid.Api.Media;
using Squid.Tests.Auth;
using Squid.Tests.Media;
using Squid.Worker.Thumbnail;
using Xunit.Abstractions;

namespace Squid.Tests.Load;

/// <summary>
/// QA-0032 (TASK-0032 AC-01) — the gap the DEV test cannot see: <c>ThumbnailTests</c> asserts the
/// image thumbnail's longest side equals <see cref="ThumbnailGenerator.MaxDimension"/> (256), and
/// the GAP-21 placeholder is itself a 256-wide PNG — so a Worker pass that registered the
/// placeholder for EVERYTHING would satisfy every assertion of that test. This scenario demands
/// the generated bytes themselves: the JPEG thumbnail must NOT be the placeholder and must carry
/// the 640×480 source's 4:3 shape scaled to <see cref="ThumbnailGenerator.MaxDimension"/>, the
/// GIF's 1×1 source must stay 1×1 (never upscaled, never the placeholder), while the video keeps
/// serving the registered placeholder through the route. If the Skia pass stops generating, this
/// test fails where the DEV test stays green.
/// </summary>
[Collection("ServiceHost")]
public sealed class QaTask0032Tests : IClassFixture<MediaHostFixture>
{
    private readonly MediaHostFixture _host;

    private readonly ITestOutputHelper _output;

    public QaTask0032Tests(MediaHostFixture host, ITestOutputHelper output)
    {
        _host = host;
        _output = output;
    }

    [Fact] // AC-01 (can-fail do QA): bytes gerados != placeholder, forma derivada da fonte
    public async Task Ac01_image_thumbnails_are_generated_skia_bytes_and_never_the_placeholder()
    {
        var (uploader, _) = await MediaHarness.SignedInAsync(_host, "thumbqa32");
        const int sourceWidth = 640;
        const int sourceHeight = 480;
        var jpeg = await HashOfAsync(await MediaHarness.UploadAsync(
            uploader, MediaHarness.JpegWithExif(sourceWidth, sourceHeight), "foto grande", "image/jpeg", "foto.jpg"));
        var gif = await HashOfAsync(await MediaHarness.UploadAsync(
            uploader, MediaHarness.MinimalGif(), "gif minimo", "image/gif", "gif.gif"));
        var video = await HashOfAsync(await MediaHarness.UploadAsync(
            uploader, MediaHarness.Mp4WithDuration(1000, 7000), "video de sete segundos", "video/mp4", "video.mp4"));

        var service = new ThumbnailService(
            _host.BlobRoot, new ThumbnailGenerator(), TimeSpan.FromHours(1),
            NullLogger<ThumbnailService>.Instance);
        Assert.Equal(3, await service.RunOnceAsync()); // jpeg + gif + video: toda mídia na primeira passada

        // JPEG: os bytes do Skia, nunca o placeholder (256x144) — a forma esperada é DERIVADA da
        // fonte 640x480 e do MaxDimension, não de um rótulo de memória.
        var jpegThumb = await File.ReadAllBytesAsync(ThumbPath(jpeg));
        Assert.False(
            jpegThumb.SequenceEqual(MediaPlaceholders.Bytes),
            "o thumbnail do JPEG deve ser a saída do Skia, não o placeholder da GAP-21");
        using (var bitmap = SKBitmap.Decode(jpegThumb))
        {
            Assert.NotNull(bitmap);
            var expectedWidth = ThumbnailGenerator.MaxDimension; // lado longo da fonte 640x480
            var expectedHeight = (int)Math.Round(sourceHeight * (double)ThumbnailGenerator.MaxDimension / sourceWidth);
            Assert.Equal((expectedWidth, expectedHeight), (bitmap!.Width, bitmap.Height));
        }

        // GIF: fonte 1x1 → thumbnail 1x1 (nunca ampliado, nunca o placeholder).
        var gifThumb = await File.ReadAllBytesAsync(ThumbPath(gif));
        Assert.False(
            gifThumb.SequenceEqual(MediaPlaceholders.Bytes),
            "o thumbnail do GIF deve ser a saída do Skia, não o placeholder da GAP-21");
        using (var bitmap = SKBitmap.Decode(gifThumb))
        {
            Assert.NotNull(bitmap);
            Assert.Equal((1, 1), (bitmap!.Width, bitmap.Height));
        }

        // Vídeo: segue o placeholder REGISTRADO — no volume e servido pela rota (GAP-21 intacta).
        Assert.Equal(MediaPlaceholders.Bytes, await File.ReadAllBytesAsync(ThumbPath(video)));
        var servedVideo = await ThumbAsync(uploader, video);
        Assert.Equal(HttpStatusCode.OK, servedVideo.StatusCode);
        Assert.Equal(IMediaStore.ThumbnailMimeType, servedVideo.Content.Headers.ContentType?.MediaType);
        Assert.Equal(MediaPlaceholders.Bytes, await servedVideo.Content.ReadAsByteArrayAsync());

        // E a rota do JPEG devolve exatamente os bytes gerados.
        var servedJpeg = await ThumbAsync(uploader, jpeg);
        Assert.Equal(HttpStatusCode.OK, servedJpeg.StatusCode);
        Assert.Equal(jpegThumb, await servedJpeg.Content.ReadAsByteArrayAsync());

        _output.WriteLine(
            $"QA-0032 thumb: jpeg={jpegThumb.Length}B {BitmapSize(jpegThumb)} gif={gifThumb.Length}B "
            + $"{BitmapSize(gifThumb)} video=placeholder {MediaPlaceholders.Bytes.Length}B "
            + $"max-dim={ThumbnailGenerator.MaxDimension}");
    }

    /// <summary>GET /api/media/{contentHash}/thumb through the caller's cookie jar.</summary>
    private static Task<HttpResponseMessage> ThumbAsync(AuthClient client, string hash) =>
        client.SendAsync(HttpMethod.Get, $"/api/media/{hash}/thumb");

    /// <summary>The contentHash of an upload answer — the route's contract body.</summary>
    private static async Task<string> HashOfAsync(HttpResponseMessage response)
    {
        Assert.Equal(HttpStatusCode.OK, response.StatusCode);
        using var json = JsonDocument.Parse(await response.Content.ReadAsStringAsync());
        return json.RootElement.GetProperty("contentHash").GetString()!;
    }

    /// <summary>Where the store reads the registered thumbnail of a hash (the volume convention).</summary>
    private string ThumbPath(string contentHash) =>
        Path.Combine(_host.BlobRoot, IMediaStore.ThumbnailFolder, contentHash);

    /// <summary>Width×height of decodable bytes, for the test log line.</summary>
    private static string BitmapSize(byte[] bytes)
    {
        using var bitmap = SKBitmap.Decode(bytes);
        return bitmap is null ? "undecodable" : $"{bitmap.Width}x{bitmap.Height}";
    }
}
